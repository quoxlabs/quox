function validateEventPayload(
  type: DomDispatchEventType,
  present: boolean,
  value: unknown,
): DomDispatchEventPayload | undefined {
  if (type === "scroll" || type === "change" || (type === "input" && !present)) {
    if (present) throw new TypeError(`quox: ${type} events must not carry a payload`);
    return undefined;
  }
  if (!present) throw new TypeError(`quox: ${type} events must carry a payload`);

  switch (type) {
    case "pointermove":
    case "pointerdown":
    case "pointerup":
    case "pointercancel":
    case "pointerenter":
    case "pointerleave":
    case "pointerover":
    case "pointerout":
    case "click":
    case "auxclick":
    case "contextmenu":
      return validatePointerPayload(value);
    case "mousemove":
    case "mousedown":
    case "mouseup":
    case "mouseenter":
    case "mouseleave":
    case "mouseover":
    case "mouseout":
    case "dblclick":
      return validateMousePayload(value);
    case "wheel":
      return validateWheelPayload(value);
    case "keydown":
    case "keyup":
      return validateKeyboardPayload(value);
    case "copy":
    case "cut":
    case "paste":
      return validateClipboardPayload(value, type);
    case "beforeinput":
    case "input":
      return validateInputPayload(value);
    case "compositionstart":
    case "compositionupdate":
    case "compositionend":
      return validateCompositionPayload(value);
    case "focus":
    case "blur":
    case "focusin":
    case "focusout":
      return validateFocusPayload(value);
    default:
      return assertNever(type);
  }
}

function assertNever(value: never): never {
  throw new TypeError(`quox: unsupported DOM dispatch event type ${value}`);
}

function assertEventType(value: unknown): DomDispatchEventType {
  if (typeof value !== "string" || !supportedEventTypes.has(value)) {
    throw new TypeError("quox: DOM dispatch event type is unsupported");
  }
  return value as DomDispatchEventType;
}

const typedArrayPrototype = Object.getPrototypeOf(Uint32Array.prototype);
const typedArrayLengthGetter = Object.getOwnPropertyDescriptor(typedArrayPrototype, "length")?.get;

function typedArrayLength(value: Uint32Array): number {
  if (typedArrayLengthGetter === undefined) {
    throw new TypeError("quox: this runtime cannot inspect a Uint32Array path");
  }
  return Reflect.apply(typedArrayLengthGetter, value, []) as number;
}

function normalizeArrayPath(value: unknown[]): readonly number[] {
  if (Object.getPrototypeOf(value) !== Array.prototype) {
    throw new TypeError("quox: DOM dispatch path must be a plain array or Uint32Array");
  }

  const descriptors = Object.getOwnPropertyDescriptors(value);
  for (const property of Reflect.ownKeys(descriptors)) {
    const descriptor = dataDescriptor(descriptors, property, `DOM dispatch path.${String(property)}`);
    if (!("value" in descriptor)) {
      throw new TypeError(`quox: DOM dispatch path.${String(property)} must not be an accessor`);
    }
  }

  const lengthValue = requiredValue(descriptors, "length", "DOM dispatch path");
  if (!Number.isSafeInteger(lengthValue) || (lengthValue as number) <= 0) {
    throw new RangeError("quox: DOM dispatch path must not be empty");
  }

  const path: number[] = [];
  for (let index = 0; index < (lengthValue as number); index += 1) {
    path.push(
      assertPositiveUint32(
        requiredValue(descriptors, String(index), "DOM dispatch path"),
        `DOM dispatch path[${index}]`,
      ),
    );
  }
  return Object.freeze(path);
}

function normalizeUint32ArrayPath(value: Uint32Array): readonly number[] {
  if (Object.getPrototypeOf(value) !== Uint32Array.prototype) {
    throw new TypeError("quox: DOM dispatch path must be a plain array or Uint32Array");
  }

  const length = typedArrayLength(value);
  if (length === 0) {
    throw new RangeError("quox: DOM dispatch path must not be empty");
  }

  const path: number[] = [];
  for (let index = 0; index < length; index += 1) {
    const descriptor = Object.getOwnPropertyDescriptor(value, String(index));
    if (descriptor === undefined || !("value" in descriptor)) {
      throw new TypeError(`quox: DOM dispatch path[${index}] must be an own data property`);
    }
    path.push(assertPositiveUint32(descriptor.value, `DOM dispatch path[${index}]`));
  }
  return Object.freeze(path);
}

function normalizePath(value: unknown): readonly number[] {
  if (Array.isArray(value)) return normalizeArrayPath(value);
  if (ArrayBuffer.isView(value) && Object.getPrototypeOf(value) === Uint32Array.prototype) {
    return normalizeUint32ArrayPath(value as Uint32Array);
  }
  throw new TypeError("quox: DOM dispatch path must be a plain array or Uint32Array");
}

function recoverInitialFrameId(value: unknown): number | undefined {
  try {
    if (typeof value !== "object" || value === null) return undefined;
    const prototype = Object.getPrototypeOf(value);
    if (prototype !== Object.prototype && prototype !== null) return undefined;
    const descriptor = Object.getOwnPropertyDescriptor(value, "frameId");
    if (descriptor === undefined || !("value" in descriptor)) return undefined;
    return assertPositiveUint32(descriptor.value, "DOM dispatch frameId");
  } catch {
    return undefined;
  }
}

/** Validate an untrusted plain step object returned across the WASM boundary. */
export function validateDomDispatchStep(value: unknown): DomDispatchStep {
  const descriptors = inspectPlainRecord(value, "DOM dispatch step");
  const kind = requiredValue(descriptors, "kind", "DOM dispatch step");
  const frameId = assertPositiveUint32(
    requiredValue(descriptors, "frameId", "DOM dispatch step"),
    "DOM dispatch frameId",
  );

  if (kind === "complete") {
    assertExactProperties(descriptors, "DOM dispatch step", COMPLETE_STEP_PROPERTIES);
    return Object.freeze({
      kind,
      frameId,
      redrawRequested: assertBoolean(
        requiredValue(descriptors, "redrawRequested", "DOM dispatch step"),
        "DOM dispatch redrawRequested",
      ),
    });
  }
  if (kind !== "event") {
    throw new TypeError('quox: DOM dispatch step kind must be "event" or "complete"');
  }

  const type = assertEventType(requiredValue(descriptors, "type", "DOM dispatch step"));
  const payloadDescriptor = Object.getOwnPropertyDescriptor(descriptors, "payload");
  const payloadless = type === "scroll" || type === "change" || (type === "input" && payloadDescriptor === undefined);
  assertExactProperties(
    descriptors,
    "DOM dispatch step",
    payloadless ? EVENT_STEP_PROPERTIES : PAYLOAD_EVENT_STEP_PROPERTIES,
  );

  const target = assertPositiveUint32(
    requiredValue(descriptors, "target", "DOM dispatch step"),
    "DOM dispatch target",
  );
  const path = normalizePath(requiredValue(descriptors, "path", "DOM dispatch step"));
  if (path[0] !== target) {
    throw new RangeError("quox: DOM dispatch path must begin with its target");
  }

  const payload = validateEventPayload(
    type,
    payloadDescriptor !== undefined,
    payloadDescriptor === undefined ? undefined : requiredValue(descriptors, "payload", "DOM dispatch step"),
  );

  const timeStamp = assertFiniteNumber(
    requiredValue(descriptors, "timeStamp", "DOM dispatch step"),
    "DOM dispatch timeStamp",
  );
  if (timeStamp < 0) {
    throw new RangeError("quox: DOM dispatch timeStamp must be nonnegative");
  }

  const step: DomDispatchEventStep = {
    kind,
    frameId,
    eventId: assertPositiveUint32(
      requiredValue(descriptors, "eventId", "DOM dispatch step"),
      "DOM dispatch eventId",
    ),
    type,
    target,
    path,
    bubbles: assertBoolean(
      requiredValue(descriptors, "bubbles", "DOM dispatch step"),
      "DOM dispatch bubbles",
    ),
    cancelable: assertBoolean(
      requiredValue(descriptors, "cancelable", "DOM dispatch step"),
      "DOM dispatch cancelable",
    ),
    composed: assertBoolean(
      requiredValue(descriptors, "composed", "DOM dispatch step"),
      "DOM dispatch composed",
    ),
    timeStamp,
  };

  return payload === undefined ? Object.freeze(step) : Object.freeze({ ...step, payload });
}

