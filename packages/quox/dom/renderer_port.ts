export interface DomDispatchEventStep<Payload = DomDispatchEventPayload> {
  readonly kind: "event";
  readonly frameId: number;
  readonly eventId: number;
  readonly type: DomDispatchEventType;
  readonly target: number;
  /** Target-first propagation path, frozen before it crosses the renderer boundary. */
  readonly path: readonly number[];
  readonly bubbles: boolean;
  readonly cancelable: boolean;
  readonly composed: boolean;
  readonly timeStamp: number;
  readonly payload?: Payload;
}

export interface DomDispatchCompleteStep {
  readonly kind: "complete";
  readonly frameId: number;
  readonly redrawRequested: boolean;
}

export type DomDispatchStep<Payload = DomDispatchEventPayload> =
  | DomDispatchEventStep<Payload>
  | DomDispatchCompleteStep;

/** A malformed initial step whose independently inspected frame ID can still be aborted. */
export class DomDispatchInitialStepError extends Error {
  readonly frameId: number;
  readonly validationError: unknown;

  constructor(frameId: number, validationError: unknown) {
    super("quox: the renderer returned a malformed initial DOM dispatch step", {
      cause: validationError,
    });
    this.name = "DomDispatchInitialStepError";
    this.frameId = frameId;
    this.validationError = validationError;
  }
}

