/** Translate the physical four-byte name advertised by the XKB key map. */
export function domCodeFromXkbName(name: string): string {
  const normalized = name.replaceAll("\0", "").trim();
  const functionKey = /^FK(\d{2})$/.exec(normalized);
  if (functionKey !== null) {
    const number = Number(functionKey[1]);
    if (number >= 1 && number <= 24) return `F${number}`;
  }
  return XKB_NAME_TO_DOM_CODE[normalized] ?? "Unidentified";
}
