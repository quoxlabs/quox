export function getDomCode(lParam: number | bigint): string {
  const rawLParam = BigInt(lParam);
  const scanCode = Number((rawLParam >> 16n) & 0xffn);
  const isExtended = ((rawLParam >> 24n) & 1n) !== 0n;
  const normalizedScanCode = isExtended ? 0xe000 | scanCode : scanCode;
  return SCAN_CODE_TO_DOM_CODE[normalizedScanCode] ?? "Unidentified";
}
